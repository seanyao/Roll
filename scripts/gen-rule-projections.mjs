#!/usr/bin/env node
/**
 * US-RULE-013 — invariant projection generator.
 *
 * The v2 `projection` fields in `policy/rules.yaml` are the SOLE authored
 * invariant prose source. This generator derives every invariant surface from
 * them — the L1 table region in `docs/verification.md`, the 行为合同 table
 * region in `docs/architecture.md`, the typed spec module
 * `packages/spec/src/generated/invariants.ts`, and the canonical fragments
 * under `docs/generated/` — so the three hand-maintained copies that could
 * silently disagree (verification table / architecture table / About page) are
 * all regenerated from one registry.
 *
 * Usage: node scripts/gen-rule-projections.mjs [--root <dir>] [--check] [--json]
 *   write (default): regenerates every output. Aborts with exit 1 and a
 *     `kind: message` on stderr BEFORE writing anything on parse /
 *     invariant-set / sentinel errors; stale outputs are repaired byte-exactly
 *     and orphan `docs/generated/*.md` files are pruned. stdout:
 *     `generated rule projections: 12 invariants`.
 *   --check: never writes. exit 0 → `rule projections ok: 12 invariants fresh`;
 *     exit 1 → each finding to stderr as `kind: message` (sorted,
 *     deterministic).
 *   --json (check or write): stdout a single JSON line
 *     `{ ok, findings: [{kind,message}], invariants:
 *     [{id,n,aboutEn,aboutZh,faultZh,expectedZh,architectureZh}] }`.
 *
 * Deterministic: no timestamps, no absolute paths, invariants ordered by
 * numeric `n` (I1→I12), findings sorted by (kind order: parse, invariant set,
 * sentinel, stale, then message localeCompare). Writing N times yields
 * byte-identical outputs; `--check --json` is byte-identical across runs.
 *
 * The script needs `@roll/spec` built (CI builds first).
 * `ROLL_SPEC_DIST` overrides the spec dist path (default
 * `<root>/packages/spec/dist/index.js`; tests simulate an unbuilt spec with it
 * and pass a fixture root via `--root`).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..");

/** The exact-twelve invariant set — the generator fails if the registry drifts. */
const EXPECTED_INVARIANT_IDS = ["I1", "I2", "I3", "I4", "I5", "I6", "I7", "I8", "I9", "I10", "I11", "I12"];

/** Sentinel marker pairs — one per doc surface (unique, greppable). */
const SENTINELS = [
  { surface: "verification", doc: "docs/verification.md" },
  { surface: "architecture", doc: "docs/architecture.md" },
];

/** The three files this generator owns inside docs/generated/. */
const GENERATED_FRAGMENTS = [
  "docs/generated/verification-invariants.md",
  "docs/generated/architecture-invariants.md",
  "docs/generated/README.md",
];

const BANNER = "<!-- GENERATED by scripts/gen-rule-projections.mjs; DO NOT EDIT. -->";

/** Deterministic finding order: matches the documented taxonomy table order. */
const KIND_ORDER = ["parse", "invariant set", "sentinel", "stale"];

function fail(message) {
  throw new Error(`gen-rule-projections: ${message}`);
}

class FindingError extends Error {
  constructor(kind, message) {
    super(message);
    this.kind = kind;
  }
}

function finding(kind, message) {
  return { kind, message };
}

function sortFindings(findings) {
  return [...findings].sort((a, b) => {
    const kindOrder = KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind);
    // Pin the locale so ordering is byte-identical across machines/ICU builds.
    return kindOrder !== 0 ? kindOrder : a.message.localeCompare(b.message, "en");
  });
}

async function loadSpec(root) {
  const dist = process.env.ROLL_SPEC_DIST || join(root, "packages", "spec", "dist", "index.js");
  if (!existsSync(dist)) {
    fail("@roll/spec not built — run `pnpm -r build` first");
  }
  return import(pathToFileURL(dist).href);
}

/**
 * Tolerant scan of the raw registry text: collects the ids of entries whose
 * block declares `kind: invariant`. Used only when the strict v2 parser
 * rejects the document (e.g. a future invariant id like I13 that
 * parseRulesV2's id pattern does not admit) so the invariant-set gate can
 * still name missing / extra ids; duplicates remain surfaced by the parser
 * itself (kind `parse`).
 */
function scanInvariantIds(text) {
  const blockPattern = /(?:^|\n)([ \t]*)- id: ([A-Za-z0-9-]+)\n/g;
  const blocks = [];
  let match;
  while ((match = blockPattern.exec(text)) !== null) {
    blocks.push({ id: match[2], start: match.index + match[0].length });
  }
  const ids = new Set();
  for (let index = 0; index < blocks.length; index += 1) {
    const end = index + 1 < blocks.length ? blocks[index + 1].start : text.length;
    if (/\bkind:\s*invariant\b/.test(text.slice(blocks[index].start, end))) {
      ids.add(blocks[index].id);
    }
  }
  return ids;
}

function invariantSetFindings(scanned, push) {
  let found = false;
  for (const id of EXPECTED_INVARIANT_IDS) {
    if (!scanned.has(id)) {
      push("invariant set", `missing invariant ${id}`);
      found = true;
    }
  }
  for (const id of [...scanned].sort()) {
    if (!EXPECTED_INVARIANT_IDS.includes(id)) {
      push("invariant set", `extra invariant ${id}`);
      found = true;
    }
  }
  return found;
}

/**
 * Load + gate the invariant set. Pushes `parse` findings (registry unreadable /
 * parseRulesV2 not ok / multi-line projection prose) and `invariant set`
 * findings (missing / extra / duplicate id), returning the ordered invariant
 * records only when no findings were pushed.
 */
async function loadInvariants(root, spec, push) {
  const registryPath = join(root, "policy", "rules.yaml");
  if (!existsSync(registryPath)) {
    push("parse", "policy/rules.yaml not found");
    return [];
  }
  const text = readFileSync(registryPath, "utf8");
  const parsed = spec.parseRulesV2(text);
  if (!parsed.ok) {
    const scanned = scanInvariantIds(text);
    if (!invariantSetFindings(scanned, push)) {
      push("parse", `policy/rules.yaml failed to parse: ${parsed.error.message}`);
    }
    return [];
  }
  const invariants = parsed.value.rules.filter((rule) => rule.kind === "invariant");
  const parseBroken = { broken: false };
  const pushParse = (message) => {
    parseBroken.broken = true;
    push("parse", message);
  };
  for (const invariant of invariants) {
    const strings = [
      invariant.projection.about.en,
      invariant.projection.about.zh,
      invariant.projection.verification.faultZh,
      invariant.projection.verification.expectedZh,
      invariant.projection.architecture.zh,
    ];
    if (strings.some((text) => /[\n\r]/.test(text))) {
      pushParse(`invariant ${invariant.id} projection must be single-line prose (contains a line break)`);
    }
  }
  if (parseBroken.broken) return [];
  const seen = new Map();
  for (const invariant of invariants) {
    if (seen.has(invariant.id)) {
      push("invariant set", `duplicate invariant ${invariant.id}`);
    }
    seen.set(invariant.id, invariant);
  }
  for (const id of EXPECTED_INVARIANT_IDS) {
    if (!seen.has(id)) push("invariant set", `missing invariant ${id}`);
  }
  for (const id of seen.keys()) {
    if (!EXPECTED_INVARIANT_IDS.includes(id)) push("invariant set", `extra invariant ${id}`);
  }
  if (push.didFind()) return [];
  return EXPECTED_INVARIANT_IDS.map((id) => seen.get(id));
}

/** 0-based start offsets of every line (each newline terminates its line). */
function lineStartOffsets(text) {
  const offsets = [0];
  for (let index = 0; index < text.length; index += 1) {
    if (text[index] === "\n") offsets.push(index + 1);
  }
  return offsets;
}

/**
 * Strict sentinel gate for one doc surface. Returns the region
 * `[startOffset, endOffsetExclusive)` (bytes, end-marker line inclusive of its
 * terminating newline) when exactly one well-ordered marker pair exists, else
 * pushes a `sentinel` finding and returns undefined.
 */
function sentinelRegion(docPath, text, surface, push) {
  const lines = text.split("\n");
  const startToken = `<!-- ROLL-INVARIANTS:${surface}:start -->`;
  const endToken = `<!-- ROLL-INVARIANTS:${surface}:end -->`;
  const startLines = [];
  const endLines = [];
  for (let index = 0; index < lines.length; index += 1) {
    if (lines[index].includes(startToken)) startLines.push(index);
    if (lines[index].includes(endToken)) endLines.push(index);
  }
  const bad = (message) => push("sentinel", `${message}: ${docPath} (${surface})`);
  if (startLines.length === 0 || endLines.length === 0) {
    bad("missing sentinel");
    return undefined;
  }
  if (startLines.length > 1 || endLines.length > 1 || endLines[0] < startLines[0]) {
    bad("duplicate sentinel");
    return undefined;
  }
  const offsets = lineStartOffsets(text);
  const startOffset = offsets[startLines[0]];
  const endOffset = offsets[endLines[0] + 1] ?? text.length;
  return [startOffset, endOffset];
}

/** Escape `|` so a projection string cannot break the generated markdown table. */
function escapeCell(text) {
  return text.replaceAll("|", "\\|");
}

function renderVerificationFragment(invariants) {
  const rows = invariants
    .map((inv) => `| ${inv.id} | ${escapeCell(inv.projection.verification.faultZh)} | ${escapeCell(inv.projection.verification.expectedZh)} |`)
    .join("\n");
  return [
    `<!-- ROLL-INVARIANTS:verification:start -->`,
    BANNER,
    `| # | 注入的故障 | 期望行为 |`,
    `|---|-----------|---------|`,
    rows,
    `<!-- ROLL-INVARIANTS:verification:end -->`,
    "",
  ].join("\n");
}

function renderArchitectureFragment(invariants) {
  const rows = invariants
    .map((inv) => `| ${inv.id} | ${escapeCell(inv.projection.architecture.zh)} |`)
    .join("\n");
  return [
    `<!-- ROLL-INVARIANTS:architecture:start -->`,
    BANNER,
    `| # | 不变量 |`,
    `|---|--------|`,
    rows,
    `<!-- ROLL-INVARIANTS:architecture:end -->`,
    "",
  ].join("\n");
}

function renderReadme(invariants) {
  const first = invariants[0]?.id ?? "";
  const last = invariants[invariants.length - 1]?.id ?? "";
  return [
    BANNER,
    "",
    "# Generated invariant projections",
    "",
    "Derived from the v2 `projection` fields in `policy/rules.yaml` (the sole authored",
    "invariant prose source) by `scripts/gen-rule-projections.mjs`. Do not edit by hand;",
    "run `node scripts/gen-rule-projections.mjs` (write) or `--check` (CI) to verify.",
    "",
    "- `verification-invariants.md` — L1 fault/expected table (embedded in `docs/verification.md`)",
    "- `architecture-invariants.md` — 行为合同 table (embedded in `docs/architecture.md`)",
    "- `packages/spec/src/generated/invariants.ts` — typed data consumed by the About page",
    "",
    `Count: ${invariants.length} invariants (${first}–${last})`,
    "",
  ].join("\n");
}

function renderInvariantsTs(invariants) {
  const lines = [];
  lines.push("/**");
  lines.push(" * @responsibility Declares the typed I1–I12 invariant projections generated from the v2 registry.");
  lines.push(" *");
  lines.push(" * AUTO-GENERATED by scripts/gen-rule-projections.mjs — DO NOT EDIT.");
  lines.push(" * The v2 `projection` fields in policy/rules.yaml are the sole authored invariant");
  lines.push(" * prose source; regenerate with `node scripts/gen-rule-projections.mjs` (CI runs");
  lines.push(" * `--check` and fails on drift).");
  lines.push(" */");
  lines.push('import type { InvariantProjection } from "../rules.js";');
  lines.push("");
  lines.push("/** One invariant's typed projection data, derived from a v2 invariant record. */");
  lines.push("export interface GeneratedInvariant {");
  lines.push('  /** Invariant id, e.g. "I1". */');
  lines.push("  readonly id: string;");
  lines.push('  /** Numeric part, e.g. 1 for "I1". */');
  lines.push("  readonly n: number;");
  lines.push("  /** Full v2 statement. */");
  lines.push("  readonly statement: string;");
  lines.push("  /** v2 projection fields (about / verification / architecture). */");
  lines.push("  readonly projection: InvariantProjection;");
  lines.push("}");
  lines.push("");
  lines.push("/** Exactly I1–I12 in numeric order — the generator fails if this set changes. */");
  lines.push("export const GENERATED_INVARIANT_IDS: readonly string[] = [");
  for (const inv of invariants) lines.push(`  ${JSON.stringify(inv.id)},`);
  lines.push("];");
  lines.push("");
  lines.push("/** The I1–I12 invariant projections, ordered by numeric id. */");
  lines.push("export const GENERATED_INVARIANTS: readonly GeneratedInvariant[] = [");
  for (const inv of invariants) {
    lines.push("  {");
    lines.push(`    id: ${JSON.stringify(inv.id)},`);
    lines.push(`    n: ${inv.n},`);
    lines.push(`    statement: ${JSON.stringify(inv.statement)},`);
    lines.push("    projection: {");
    lines.push("      about: {");
    lines.push(`        en: ${JSON.stringify(inv.projection.about.en)},`);
    lines.push(`        zh: ${JSON.stringify(inv.projection.about.zh)},`);
    lines.push("      },");
    lines.push("      verification: {");
    lines.push(`        faultZh: ${JSON.stringify(inv.projection.verification.faultZh)},`);
    lines.push(`        expectedZh: ${JSON.stringify(inv.projection.verification.expectedZh)},`);
    lines.push("      },");
    lines.push("      architecture: {");
    lines.push(`        zh: ${JSON.stringify(inv.projection.architecture.zh)},`);
    lines.push("      },");
    lines.push("    },");
    lines.push("  },");
  }
  lines.push("];");
  return lines.join("\n") + "\n";
}

function invariantJson(inv) {
  return {
    id: inv.id,
    n: inv.n,
    aboutEn: inv.projection.about.en,
    aboutZh: inv.projection.about.zh,
    faultZh: inv.projection.verification.faultZh,
    expectedZh: inv.projection.verification.expectedZh,
    architectureZh: inv.projection.architecture.zh,
  };
}

/**
 * Shared pipeline: load spec → parse registry → exact-twelve gate → strict
 * sentinel gate → render every output. Structural findings (parse / invariant
 * set / sentinel) are pushed; renders are returned for the caller to write or
 * compare. Stale comparisons (fragments, doc regions, the TS module, orphans)
 * are the caller's job and only run when no structural finding exists.
 */
async function computeProjections(root, push) {
  const spec = await loadSpec(root);
  const invariants = await loadInvariants(root, spec, push);
  const modulePath = "packages/spec/src/generated/invariants.ts";
  const renders = { invariants, modulePath };
  if (push.didFind()) return renders;

  for (const inv of invariants) {
    inv.n = Number(inv.id.slice(1));
  }

  const docs = new Map();
  for (const { surface, doc } of SENTINELS) {
    const docPath = join(root, doc);
    if (!existsSync(docPath)) {
      push("sentinel", `missing sentinel: ${doc} (${surface})`);
      continue;
    }
    const text = readFileSync(docPath, "utf8");
    const region = sentinelRegion(doc, text, surface, push);
    if (region !== undefined) docs.set(doc, { text, region });
  }
  if (push.didFind()) return renders;

  renders.verificationFragment = renderVerificationFragment(invariants);
  renders.architectureFragment = renderArchitectureFragment(invariants);
  renders.readme = renderReadme(invariants);
  renders.invariantsTs = renderInvariantsTs(invariants);
  renders.docs = docs;
  return renders;
}

/** Write mode: throws on the first structural finding, then writes + prunes. */
export async function generateRuleProjections(root) {
  const findings = [];
  const push = (kind, message) => findings.push(finding(kind, message));
  push.didFind = () => findings.length > 0;
  const renders = await computeProjections(root, push);
  const first = sortFindings(findings)[0];
  if (first) throw new FindingError(first.kind, first.message);

  const generatedDir = join(root, "docs", "generated");
  mkdirSync(generatedDir, { recursive: true });
  const expectedFragments = new Set(GENERATED_FRAGMENTS);
  for (const entry of readdirSync(generatedDir, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
    const file = `docs/generated/${entry.name}`;
    if (!expectedFragments.has(file)) rmSync(join(generatedDir, entry.name));
  }
  writeFileSync(join(root, "docs/generated/verification-invariants.md"), renders.verificationFragment);
  writeFileSync(join(root, "docs/generated/architecture-invariants.md"), renders.architectureFragment);
  writeFileSync(join(root, "docs/generated/README.md"), renders.readme);

  const modulePath = join(root, renders.modulePath);
  mkdirSync(dirname(modulePath), { recursive: true });
  writeFileSync(modulePath, renders.invariantsTs);

  for (const { surface, doc } of SENTINELS) {
    const { text, region } = renders.docs.get(doc);
    const [start, end] = region;
    writeFileSync(join(root, doc), `${text.slice(0, start)}${renders[`${surface}Fragment`]}${text.slice(end)}`);
  }
  return renders.invariants;
}

/** Check mode: never writes; reports every finding (including stale/orphan). */
export async function checkRuleProjections(root) {
  const findings = [];
  const push = (kind, message) => findings.push(finding(kind, message));
  push.didFind = () => findings.length > 0;
  const renders = await computeProjections(root, push);

  if (findings.length === 0) {
    const fragments = new Map([
      ["docs/generated/verification-invariants.md", renders.verificationFragment],
      ["docs/generated/architecture-invariants.md", renders.architectureFragment],
      ["docs/generated/README.md", renders.readme],
    ]);
    for (const [file, expected] of fragments) {
      const full = join(root, file);
      if (!existsSync(full) || readFileSync(full, "utf8") !== expected) {
        findings.push(finding("stale", `stale fragment: ${file}`));
      }
    }
    const modulePath = join(root, renders.modulePath);
    if (!existsSync(modulePath) || readFileSync(modulePath, "utf8") !== renders.invariantsTs) {
      findings.push(finding("stale", `stale module: ${renders.modulePath}`));
    }
    for (const { surface, doc } of SENTINELS) {
      const { text, region } = renders.docs.get(doc);
      const [start, end] = region;
      if (text.slice(start, end) !== renders[`${surface}Fragment`]) {
        findings.push(finding("stale", `stale region: ${doc} (${surface})`));
      }
    }
    const generatedDir = join(root, "docs", "generated");
    if (existsSync(generatedDir)) {
      for (const entry of readdirSync(generatedDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
        const file = `docs/generated/${entry.name}`;
        if (!fragments.has(file)) findings.push(finding("stale", `orphan output: ${file}`));
      }
    }
  }

  const sorted = sortFindings(findings);
  return {
    ok: sorted.length === 0,
    findings: sorted,
    invariants: renders.invariants.map(invariantJson),
  };
}

function parseArgs(argv) {
  const options = { root: undefined, check: false, json: false };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--root") options.root = argv[++index];
    else if (arg === "--check") options.check = true;
    else if (arg === "--json") options.json = true;
    else fail(`usage: node scripts/gen-rule-projections.mjs [--root <directory>] [--check] [--json] (unknown argument: ${arg})`);
  }
  return options;
}

async function cli() {
  const options = parseArgs(process.argv.slice(2));
  const root = resolve(options.root ?? process.cwd());

  if (options.check) {
    const result = await checkRuleProjections(root);
    if (options.json) {
      process.stdout.write(`${JSON.stringify({ ok: result.ok, findings: result.findings, invariants: result.invariants })}\n`);
    } else if (result.ok) {
      process.stdout.write(`rule projections ok: ${result.invariants.length} invariants fresh\n`);
    } else {
      for (const item of result.findings) process.stderr.write(`${item.kind}: ${item.message}\n`);
    }
    if (!result.ok) process.exitCode = 1;
    return;
  }

  let invariants;
  try {
    invariants = await generateRuleProjections(root);
  } catch (error) {
    // --json (write mode) still emits the single JSON line on a gate failure.
    if (options.json && error instanceof FindingError) {
      process.stdout.write(
        `${JSON.stringify({ ok: false, findings: [finding(error.kind, error.message)], invariants: [] })}\n`,
      );
      process.exitCode = 1;
      return;
    }
    throw error;
  }
  if (options.json) {
    process.stdout.write(
      `${JSON.stringify({ ok: true, findings: [], invariants: invariants.map(invariantJson) })}\n`,
    );
  } else {
    process.stdout.write(`generated rule projections: ${invariants.length} invariants\n`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    await cli();
  } catch (error) {
    if (error instanceof FindingError) {
      process.stderr.write(`${error.kind}: ${error.message}\n`);
    } else {
      process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    }
    process.exitCode = 1;
  }
}
